import { get, post, route } from 'remix/routes'

export const routes = route({
  assets: get('/assets/*path'),
  home: '/',
  auth: route('auth', {
    discord: get('discord'),
    discordCallback: get('discord/callback'),
    logout: post('logout'),
  }),
  admin: route('admin', {
    newLeague: get('leagues/new'),
    createLeague: post('leagues/new'),
  }),
  runnerApi: route('api/v1/runner', {
    register: post('register'),
    heartbeat: post('heartbeat'),
    claim: post('claim'),
    configuration: get('attempts/:attemptId/configuration'),
    telemetry: post('attempts/:attemptId/telemetry'),
    updateLease: post('leases/:leaseId'),
  }),
  leagues: route('leagues', {
    show: get(':leagueSlug'),
    updatePublication: post(':leagueSlug/publication'),
    operations: route(':leagueSlug/operations', {
      dashboard: get('/'),
      setDeadline: post('deadlines'),
      proposeTrade: post('trades'),
      reviewTrade: post('trades/:proposalId/review'),
      cancelTrade: post('trades/:proposalId/cancel'),
      scheduleMatch: post('matches'),
      queueAttempt: post('matches/:matchId/attempts'),
      issueCredential: post('runner-credentials'),
      revokeStation: post('runner-stations/:stationId/revoke'),
      deriveTelemetry: post('attempts/:attemptId/telemetry/derive'),
      correctTelemetry: post('attempts/:attemptId/telemetry/corrections'),
      confirmTelemetry: post('attempts/:attemptId/telemetry/confirm'),
    }),
    content: route(':leagueSlug/content', {
      dashboard: get('/'),
      create: post('/'),
      uploadAsset: post('assets'),
      assignAsset: post('revisions/:revisionId/assets'),
      publish: post('revisions/:revisionId/publish'),
      clone: post('revisions/:revisionId/clone'),
    }),
    drafts: route(':leagueSlug/drafts', {
      dashboard: get('/'),
      create: post('/'),
      room: get(':draftId'),
      start: post(':draftId/start'),
      pick: post(':draftId/picks'),
      pause: post(':draftId/pause'),
      resume: post(':draftId/resume'),
      automaticPick: post(':draftId/automatic-pick'),
      reversePick: post(':draftId/reverse-pick'),
      updateQueue: post(':draftId/teams/:teamId/queue'),
    }),
    configuration: route(':leagueSlug/configuration', {
      dashboard: get('/'),
      preview: post('preview'),
      createStatProfile: post('stat-profiles'),
      importStatEditor: post('imports/stat-editor-v4'),
      showStatProfile: get('stat-profiles/:revisionId'),
      updateStatProfile: post('stat-profiles/:revisionId'),
      publishStatProfile: post('stat-profiles/:revisionId/publish'),
      cloneStatProfile: post('stat-profiles/:revisionId/clone'),
      createRuleset: post('rulesets'),
      showRuleset: get('rulesets/:revisionId'),
      updateRuleset: post('rulesets/:revisionId'),
      publishRuleset: post('rulesets/:revisionId/publish'),
      cloneRuleset: post('rulesets/:revisionId/clone'),
      createLineup: post('teams/:teamId/lineups'),
      importAutoTeam: post('teams/:teamId/imports/auto-team'),
      showLineup: get('teams/:teamId/lineups/:revisionId'),
      updateLineup: post('teams/:teamId/lineups/:revisionId'),
      publishLineup: post('teams/:teamId/lineups/:revisionId/publish'),
      cloneLineup: post('teams/:teamId/lineups/:revisionId/clone'),
    }),
  }),
})
